import csv
import io
import re
import time
import joblib
import numpy as np
import pandas as pd
from backend.app.lab_config import read_json
from .data import digest
from .engine import runtime

class Models:
    def __init__(self, project):
        self.project=project
        self.root=project/'model_registry'

    def get(self,key):
        if not re.fullmatch('[a-f0-9]{32}',key):
            raise ValueError('无效模型ID')
        folder=self.root/key
        if not (folder/'metadata.json').is_file():
            raise ValueError('模型不存在')
        meta=read_json(folder/'metadata.json')
        task_id=meta['source_experiment_id']
        if not re.fullmatch('[a-f0-9]{32}',task_id):
            raise ValueError('无效模型来源')
        source=self.project/'experiment_runs'/task_id
        if read_json(source/'state.json')['status']!='completed' or key not in read_json(source/'results.json').get('model_ids',[]):
            raise ValueError('来源实验未完成或未通过注册验证')
        if meta['model_id']!=key or digest(folder/'pipeline.joblib')!=meta['artifact_sha256']:
            raise ValueError('模型完整性检查失败')
        return meta

    def list(self,dataset_id=None):
        result=[]
        if self.root.exists():
            for path in self.root.iterdir():
                if re.fullmatch('[a-f0-9]{32}',path.name):
                    try:
                        meta=self.get(path.name)
                        if dataset_id is None or meta['dataset_id']==dataset_id:
                            result.append({k:v for k,v in meta.items() if k!='feature_names'})
                    except (ValueError, OSError, KeyError):
                        pass
        return result

    def predict(self,key,dataset_id,payload):
        meta=self.get(key)
        if meta['dataset_id']!=dataset_id:
            raise ValueError('不同数据集禁止交叉使用模型')
        if meta['runtime_versions']!=runtime():
            raise ValueError('模型运行库版本不符，请使用训练时环境')
        text=payload.decode('utf-8-sig')
        header=next(csv.reader(io.StringIO(text)),[])
        if len(header)!=len(set(header)):
            raise ValueError('CSV存在重复特征列')
        frame=pd.read_csv(io.StringIO(text))
        if len(frame)!=1:
            raise ValueError('仅接受一个样本行')
        sample_id=str(frame.pop('sample_id').iloc[0]) if 'sample_id' in frame else 'uploaded_sample'
        if set(frame.columns)!=set(meta['feature_names']):
            missing=set(meta['feature_names'])-set(frame.columns)
            extra=set(frame.columns)-set(meta['feature_names'])
            raise ValueError(f'特征清单不匹配：缺少{len(missing)}列，多出{len(extra)}列')
        values=frame[meta['feature_names']].to_numpy(dtype=float)
        if not np.isfinite(values).all():
            raise ValueError('输入包含缺失值或无穷值')
        started=time.perf_counter()
        # Only artifacts generated by a completed trusted worker are eligible; uploads never reach joblib.
        artifact=self.root/key/'pipeline.joblib'
        model=joblib.load(artifact)
        from threadpoolctl import threadpool_limits
        with threadpool_limits(limits=1):
            predicted=str(model.predict(values)[0])
        return {'dataset_id':dataset_id,'dataset_version':meta['dataset_version'],'model_id':key,'model_name':meta['algorithm'],
                'model_version':meta['model_version'],'sample_id':sample_id,'predicted_class':predicted,
                'input_feature_count':len(meta['feature_names']),'selected_feature_count':meta['n_features'],
                'inference_seconds':time.perf_counter()-started,'probability_output':False}
